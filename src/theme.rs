//! Semantic colour tokens and the themes (Light / Dark / Custom).
//!
//! Two strictly separate visual layers share this palette:
//! * **chrome** — ribbon, tabs, status bar, ruler, dialogs, menus; and
//! * **sheet**  — the page/canvas the document is drawn on.
//!
//! Nothing in the UI may hard-code a colour; every value comes from `Tokens`.
//! `pdf.rs` is deliberately excluded: the exported PDF stays black-on-white.
//!
//! The Custom theme exposes only the main components ([`CustomPalette`]); every
//! other token is derived in [`CustomPalette::tokens`]. New editable components
//! are added by extending the `custom_palette!` list at the bottom of the struct
//! definition — the editor and the settings file pick them up automatically.

use eframe::egui::{self, Color32, Stroke, vec2};
use serde::{Deserialize, Serialize};

/// Semantic colour tokens. Chrome and sheet are independent by design; the
/// dark sheet is never produced by inverting the light one.
#[derive(Clone, Copy)]
pub struct Tokens {
    // ---- CHROME ----
    pub chrome_bg: Color32,
    pub chrome_bg_alt: Color32,
    pub chrome_fg: Color32,
    pub chrome_fg_muted: Color32,
    pub chrome_accent: Color32,
    pub chrome_accent_hover: Color32,
    pub chrome_accent_fg: Color32,
    pub chrome_border: Color32,
    pub chrome_icon: Color32,
    pub chrome_icon_active: Color32,
    pub chrome_hover_bg: Color32,
    pub chrome_active_bg: Color32,
    /// Selection inside chrome lists (navigation, spelling suggestions, menus).
    /// Kept separate from the page text selection so both layers stay independent.
    pub chrome_selection_bg: Color32,
    pub chrome_selection_fg: Color32,
    pub status_bg: Color32,
    pub status_fg: Color32,
    // ---- SHEET ----
    /// Desk/canvas behind the pages (independent of the page itself).
    pub desk_bg: Color32,
    pub sheet_bg: Color32,
    pub sheet_fg: Color32,
    pub sheet_fg_muted: Color32,
    pub sheet_border: Color32,
    pub sheet_shadow: Color32,
    pub caret: Color32,
    pub selection_bg: Color32,
    /// Foreground for selected text (selection is drawn as a background, so the
    /// text keeps its own colour; kept for themes that paint selected glyphs).
    #[allow(dead_code)]
    pub selection_fg: Color32,
    pub search_highlight: Color32,
    pub margin_guide: Color32,
    pub grid_line: Color32,
    // ---- RULER ----
    pub ruler_bg: Color32,
    pub ruler_page_band: Color32,
    pub ruler_content: Color32,
    pub ruler_tick: Color32,
    pub ruler_indent_marker: Color32,
    // ---- UI auxiliar ----
    /// Dedicated tooltip surface, painted explicitly instead of relying on
    /// egui's shared popup `window_fill`.
    pub tooltip_bg: Color32,
    pub tooltip_fg: Color32,
    pub dialog_bg: Color32,
    /// Dialog foreground (equals `chrome_fg`; kept as its own semantic token).
    #[allow(dead_code)]
    pub dialog_fg: Color32,
    pub warning: Color32,
    pub error: Color32,
    // ---- COMENTARIOS ----
    pub comment_card_bg: Color32,
    pub comment_card_border: Color32,
    pub comment_card_fg: Color32,
}

