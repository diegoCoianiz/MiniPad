/// One row of the Custom theme editor. The declarative table generated by
/// `custom_palette!` drives the UI, so adding a field is enough for it to show
/// up automatically (and, with `#[serde(default)]`, old settings keep loading).
pub struct CustomField {
    pub group: &'static str,
    pub key: &'static str,
    pub label: &'static str,
}

/// Generates the user-editable palette, its defaults, the key-based accessors
/// used by the editor and the ordered field table.
macro_rules! custom_palette {
    ($(($group:literal, $field:ident, $label:literal),)*) => {
        #[derive(Clone, Copy, PartialEq, Debug, Serialize, Deserialize)]
        #[serde(default)]
        pub struct CustomPalette {
            $(#[serde(with = "hex_color")] pub $field: Color32,)*
        }

        impl Default for CustomPalette {
            fn default() -> Self {
                let t = light();
                Self { $($field: t.$field,)* }
            }
        }

        impl CustomPalette {
            /// Copies the main components out of a fully resolved theme (used to
            /// seed the palette from Light/Dark or from the active theme).
            pub fn from_tokens(t: &Tokens) -> Self {
                Self { $($field: t.$field,)* }
            }

            pub fn get(&self, key: &str) -> Option<Color32> {
                match key {
                    $(stringify!($field) => Some(self.$field),)*
                    _ => None,
                }
            }

            pub fn set(&mut self, key: &str, c: Color32) {
                match key {
                    $(stringify!($field) => self.$field = c,)*
                    _ => {}
                }
            }
        }

        pub const CUSTOM_FIELDS: &[CustomField] = &[
            $(CustomField { group: $group, key: stringify!($field), label: $label },)*
        ];
    };
}

