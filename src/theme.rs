/// Installs the theme into egui. `Visuals::dark()`/`light()` are only the base
/// palette here — every token that matters is overwritten explicitly.
pub fn apply_theme(ctx: &egui::Context, theme: &Theme) {
    let t = &theme.tokens;
    let mut v = if theme.is_dark() { egui::Visuals::dark() } else { egui::Visuals::light() };

    // Backgrounds and surfaces.
    v.panel_fill = t.chrome_bg;
    v.window_fill = t.dialog_bg;
    v.extreme_bg_color = t.chrome_bg_alt;
    v.faint_bg_color = t.chrome_bg_alt;
    v.code_bg_color = t.chrome_bg_alt;

    // Text.
    v.override_text_color = Some(t.chrome_fg);
    v.widgets.noninteractive.fg_stroke.color = t.chrome_fg_muted;
    v.widgets.inactive.fg_stroke.color = t.chrome_fg;
    v.widgets.hovered.fg_stroke.color = t.chrome_fg;
    v.widgets.active.fg_stroke.color = t.chrome_accent_fg;

    // Widget backgrounds.
    v.widgets.noninteractive.bg_fill = t.chrome_bg;
    v.widgets.inactive.weak_bg_fill = t.chrome_bg_alt;
    v.widgets.inactive.bg_fill = t.chrome_bg_alt;
    v.widgets.hovered.weak_bg_fill = t.chrome_hover_bg;
    v.widgets.hovered.bg_fill = t.chrome_hover_bg;
    v.widgets.active.weak_bg_fill = t.chrome_active_bg;
    v.widgets.active.bg_fill = t.chrome_active_bg;

    // Borders.
    v.widgets.noninteractive.bg_stroke.color = t.chrome_border;
    v.widgets.inactive.bg_stroke.color = t.chrome_border;
    v.widgets.hovered.bg_stroke.color = t.chrome_accent;
    v.widgets.active.bg_stroke.color = t.chrome_accent;

    // Selection for chrome widgets (menus, lists, selected labels). The page
    // text selection is painted separately with `selection_bg`/`caret`.
    v.selection.bg_fill = t.chrome_selection_bg;
    v.selection.stroke = Stroke::new(1.0, t.chrome_selection_fg);

    // Windows / dialogs / tooltips.
    v.window_stroke = Stroke::new(1.0, t.chrome_border);
    v.window_shadow.color = t.sheet_shadow;
    v.popup_shadow.color = t.sheet_shadow;

    ctx.set_visuals(v);
    // Helpers reach the active tokens through egui's memory (`theme_for`).
    ctx.data_mut(|d| d.insert_temp(egui::Id::new(ACTIVE_THEME_ID), *theme));
    ctx.global_style_mut(|s| {
        s.spacing.button_padding = vec2(6.0, 3.0);
        s.spacing.item_spacing = vec2(4.0, 4.0);
    });
}

// ================================================================ colour maths

/// Perceived luma of `c` in `0.0..=1.0` (sRGB, not linearised).
fn luma(c: Color32) -> f32 {
    (0.2126 * c.r() as f32 + 0.7152 * c.g() as f32 + 0.0722 * c.b() as f32) / 255.0
}

/// Mixes `a` towards `b` by `t` in `0.0..=1.0`, keeping `a`'s alpha.
pub fn mix(a: Color32, b: Color32, t: f32) -> Color32 {
    let t = t.clamp(0.0, 1.0);
    let f = |x: u8, y: u8| (x as f32 + (y as f32 - x as f32) * t).round() as u8;
    Color32::from_rgba_unmultiplied(f(a.r(), b.r()), f(a.g(), b.g()), f(a.b(), b.b()), a.a())
}

/// WCAG relative luminance (sRGB linearised).
fn rel_lum(c: Color32) -> f32 {
    fn ch(v: u8) -> f32 {
        let s = v as f32 / 255.0;
        if s <= 0.04045 { s / 12.92 } else { ((s + 0.055) / 1.055).powf(2.4) }
    }
    0.2126 * ch(c.r()) + 0.7152 * ch(c.g()) + 0.0722 * ch(c.b())
}

/// WCAG contrast ratio between two opaque colours (1.0..=21.0).
pub fn contrast_ratio(a: Color32, b: Color32) -> f32 {
    let (la, lb) = (rel_lum(a), rel_lum(b));
    let (hi, lo) = if la > lb { (la, lb) } else { (lb, la) };
    (hi + 0.05) / (lo + 0.05)
}

/// Returns white or MiniPad's dark ink, whichever reads better on `bg`.
pub fn readable_on(bg: Color32) -> Color32 {
    let light = rgb(0xFF, 0xFF, 0xFF);
    let dark = rgb(0x1F, 0x23, 0x28);
    if contrast_ratio(dark, bg) >= contrast_ratio(light, bg) { dark } else { light }
}

/// HSV saturation of `c` in `0.0..=1.0`.
fn saturation(c: Color32) -> f32 {
    let (r, g, b) = (c.r() as f32, c.g() as f32, c.b() as f32);
    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    if max <= 0.0 { 0.0 } else { (max - min) / max }
}

/// Mixes each channel towards white by `t`, keeping the hue.
fn lighten_preserve_hue(c: Color32, t: f32) -> Color32 {
    let f = |v: u8| (v as f32 + (255.0 - v as f32) * t).clamp(0.0, 255.0) as u8;
    Color32::from_rgba_unmultiplied(f(c.r()), f(c.g()), f(c.b()), c.a())
}

/// Scales each channel towards black by `t`, keeping the hue.
fn darken_preserve_hue(c: Color32, t: f32) -> Color32 {
    let f = |v: u8| (v as f32 * (1.0 - t)).clamp(0.0, 255.0) as u8;
    Color32::from_rgba_unmultiplied(f(c.r()), f(c.g()), f(c.b()), c.a())
}

/// Remaps a *document* colour so it stays legible on the dark sheet, without
/// ever touching the colour stored in the document (or the PDF).
///
/// Neutral near-black (the document default) becomes the sheet foreground and
/// neutral near-white surfaces become a dark surface; chromatic colours keep
/// their hue and are only lightened/deepened when they sit at the extremes.
pub fn remap_for_dark_sheet(col: Color32, t: &Tokens) -> Color32 {
    if col.a() == 0 {
        return col;
    }
    let l = luma(col);
    let s = saturation(col);
    if s < 0.15 {
        // Neutral greys: pull the extremes onto readable sheet surfaces.
        if l < 0.30 {
            return t.sheet_fg;
        }
        if l > 0.80 {
            return t.chrome_bg_alt;
        }
        return col;
    }
    // Chromatic colours: keep the hue, move away from the extremes.
    if l < 0.40 {
        return lighten_preserve_hue(col, 0.55);
    }
    if l > 0.85 {
        return darken_preserve_hue(col, 0.55);
    }
    col
}

/// Whether `theme` uses a dark sheet (and therefore needs remapping). Derived
/// from the sheet itself, so a Custom theme can mix a dark page with a light
/// chrome or vice versa.
pub fn is_dark_sheet(theme: &Theme) -> bool {
    luma(theme.tokens.sheet_bg) < 0.5
}

#[cfg(test)]
mod tests {
    use super::*;

    fn check(name: &str, fg: Color32, bg: Color32) -> f32 {
        let r = contrast_ratio(fg, bg);
        assert!(r >= 4.5, "{name}: contrast {r:.2}:1 is below WCAG AA (4.5:1)");
        r
    }

    #[test]
    fn critical_pairs_meet_wcag_aa() {
        for theme in [Theme::light(), Theme::dark()] {
            let t = theme.tokens;
            check("chrome_fg/chrome_bg", t.chrome_fg, t.chrome_bg);
            check("sheet_fg/sheet_bg", t.sheet_fg, t.sheet_bg);
            check("chrome_accent_fg/chrome_accent", t.chrome_accent_fg, t.chrome_accent);
            check("chrome_selection_fg/chrome_selection_bg", t.chrome_selection_fg, t.chrome_selection_bg);
            check("status_fg/status_bg", t.status_fg, t.status_bg);
            check("dialog_fg/dialog_bg", t.dialog_fg, t.dialog_bg);
            check("tooltip_fg/tooltip_bg", t.tooltip_fg, t.tooltip_bg);
        }
    }

    #[test]
    fn dark_remap_maps_default_ink_to_sheet_fg() {
        let t = dark();
        assert_eq!(remap_for_dark_sheet(Color32::BLACK, &t), t.sheet_fg);
        // A chromatic colour keeps its hue (red stays red).
        let red = Color32::from_rgb(0xC0, 0x00, 0x00);
        let r = remap_for_dark_sheet(red, &t);
        assert!(r.r() > r.g() && r.r() > r.b() && r.r() > 0xC0);
        // Fully transparent colours pass through untouched.
        assert_eq!(remap_for_dark_sheet(Color32::TRANSPARENT, &t), Color32::TRANSPARENT);
    }

    #[test]
    fn light_and_dark_are_distinct() {
        assert_ne!(light().chrome_bg, dark().chrome_bg);
        assert_ne!(light().sheet_bg, dark().sheet_bg);
        assert!(Theme::dark().is_dark());
        assert!(!Theme::light().is_dark());
    }

    #[test]
    fn custom_palette_round_trips_hex() {
        let mut p = CustomPalette::from_tokens(&dark());
        p.chrome_accent = Color32::from_rgb(0x12, 0x34, 0x56);
        let json = serde_json::to_string(&p).unwrap();
        assert!(json.contains("\"#123456\""), "colours are stored as hex: {json}");
        let back: CustomPalette = serde_json::from_str(&json).unwrap();
        assert_eq!(back, p);

        // Missing fields (an older settings file) fall back to the defaults.
        let partial: CustomPalette = serde_json::from_str(r##"{"chrome_bg":"#010203"}"##).unwrap();
        assert_eq!(partial.chrome_bg, Color32::from_rgb(1, 2, 3));
        assert_eq!(partial.sheet_bg, light().sheet_bg);
    }

    #[test]
    fn custom_fields_cover_the_palette() {
        let mut p = CustomPalette::default();
        for f in CUSTOM_FIELDS {
            let c = p.get(f.key).expect("every table key resolves");
            let n = Color32::from_rgb(c.r().wrapping_add(1), c.g(), c.b());
            p.set(f.key, n);
            assert_eq!(p.get(f.key), Some(n));
        }
        let mut keys: Vec<_> = CUSTOM_FIELDS.iter().map(|f| f.key).collect();
        keys.sort();
        keys.dedup();
        assert_eq!(keys.len(), CUSTOM_FIELDS.len(), "field keys are unique");
    }

    #[test]
    fn custom_palette_derives_readable_colors() {
        let mut p = CustomPalette::default();
        p.chrome_accent = Color32::from_rgb(0xFF, 0xEE, 0x00);
        assert_eq!(p.tokens().chrome_accent_fg, Color32::from_rgb(0x1F, 0x23, 0x28));
        assert_eq!(p.tokens().chrome_icon_active, p.tokens().chrome_accent_fg);

        p.chrome_accent = Color32::from_rgb(0x10, 0x20, 0x40);
        assert_eq!(p.tokens().chrome_accent_fg, Color32::WHITE);

        p.status_bg = Color32::from_rgb(0xF0, 0xF0, 0xF0);
        assert_eq!(p.tokens().status_fg, Color32::from_rgb(0x1F, 0x23, 0x28));

        p.chrome_selection_bg = Color32::from_rgb(0x10, 0x20, 0x40);
        assert_eq!(p.tokens().chrome_selection_fg, Color32::WHITE);
        p.chrome_selection_bg = Color32::from_rgb(0xF2, 0xE6, 0xB0);
        assert_eq!(p.tokens().chrome_selection_fg, Color32::from_rgb(0x1F, 0x23, 0x28));
    }

    #[test]
    fn custom_sheet_darkness_drives_remap() {
        let mut p = CustomPalette::default();
        assert!(!is_dark_sheet(&Theme::custom(&p)));
        p.sheet_bg = Color32::from_rgb(0x10, 0x10, 0x10);
        p.sheet_fg = Color32::from_rgb(0xEE, 0xEE, 0xEE);
        let th = Theme::custom(&p);
        assert!(is_dark_sheet(&th));
        assert_eq!(remap_for_dark_sheet(Color32::BLACK, &th.tokens), th.tokens.sheet_fg);
    }

    #[test]
    fn theme_for_reads_active_theme_from_context() {
        let ctx = egui::Context::default();
        let mut p = CustomPalette::default();
        p.chrome_bg = Color32::from_rgb(0x40, 0x20, 0x60);
        let theme = Theme::custom(&p);
        apply_theme(&ctx, &theme);
        let mut seen = None;
        let mut out = ctx.run_ui(egui::RawInput::default(), |ui| {
            seen = Some(theme_for(ui));
        });
        out.textures_delta.clear();
        let seen = seen.expect("a frame was produced");
        assert_eq!(seen.name, ThemeName::Custom);
        assert_eq!(seen.tokens.chrome_bg, p.chrome_bg);
    }
}
